# ── 月亮 ─────────────────────────────────────────────────────
NEW_MOON_EPOCH = datetime(2000, 1, 6, 18, 14)  # 基准新月（UTC）
SYNODIC = 29.53058867  # 朔望月天数


def day_part(h: int) -> str:
    """一天五段：晨 5-10 / 午 11-16 / 晚 17-20 / 夜 21-1 / 凌晨 2-4"""
    if 5 <= h < 11:
        return "morning"
    if 11 <= h < 17:
        return "noon"
    if 17 <= h < 21:
        return "evening"
    if 2 <= h < 5:
        return "predawn"
    return "night"


def zhongqiu_span(year: int):
    s = ZHONGQIU.get(year)
    if not s:
        return None, None
    d1 = date(year, *s)
    return d1, d1 + timedelta(days=1)


# ── 洗牌抽卡：翻完一轮才重洗，一轮内每张必出且只出一次 ──────
_draw_piles: dict[str, list[str]] = {}


def draw(deck: str, cards: list[str]) -> str:
    pile = _draw_piles.get(deck)
    if not pile:
        pile = list(cards)
        random.shuffle(pile)
    card = pile.pop()
    _draw_piles[deck] = pile
    return card


def scene_text(d: date, hour: int) -> str:
    d1, d2 = zhongqiu_span(d.year)
    part = day_part(hour)
    if d1 is None:
        return draw(f"quiet:{part}", QUIET_CARDS[part])
    if d == d1 - timedelta(days=1):
        return draw("eve", EVE_CARDS)
    if d == d1:
        night_side = part in ("evening", "night", "predawn")
        return draw("day:night" if night_side else "day:day",
                    DAY_CARDS if night_side else DAY_DAY_CARDS)
    if d == d2:
        return draw("day2", DAY2_CARDS)
    if d1 - timedelta(days=5) <= d < d1 - timedelta(days=1):
        return NEAR_BEFORE
    if d2 < d <= d2 + timedelta(days=3):
        return NEAR_AFTER
    return draw(f"quiet:{part}", QUIET_CARDS[part])


def moon_text(d: date, city: str = "佛山") -> str:
    d1, d2 = zhongqiu_span(d.year)
    if d1 is not None and d1 - timedelta(days=1) <= d <= d2 + timedelta(days=1):
        if d == d1 - timedelta(days=1):
            return "明天中秋。月亮已经差不多圆了，今晚从东边上来，缺的那一点点几乎看不出来。"
        if d == d1:
            return "今晚满月。日落时分从正东边升起来，整夜都在，天亮前才落。中秋的月亮就是这样陪着人过夜的。"
        if d == d2:
            return "追月。十六的月亮可能比十五还圆一点，升起得比昨晚迟一些。天台的桌子可以再摆一晚。"
        return "月亮开始亏了，亏得很慢，肉眼看不出来。它今晚升得更迟，后半夜才高。"
    days = (datetime.combine(d, datetime.min.time()) - NEW_MOON_EPOCH).total_seconds() / 86400.0
    age = days % SYNODIC
    illum = (1 - math.cos(2 * math.pi * age / SYNODIC)) / 2
    if age < 1.5 or age > 28.0:
        shape = "新月，天上几乎找不到它"
    elif age < 6:
        shape = "娥眉月，细细一钩"
    elif age < 8.5:
        shape = "上弦月，半圆，像被切了一刀"
    elif age < 13.5:
        shape = "盈凸月，鼓着往圆走"
    elif age < 16:
        shape = "满月前后，整夜亮着"
    elif age < 21.5:
        shape = "亏凸月，开始瘦了"
    elif age < 24:
        shape = "下弦月，后半夜才出来"
    else:
        shape = "残月，天亮前挂在东边"
    return f"月亮{age:.0f}天大，照亮{illum:.0%}，{shape}。今晚几点升，能联网就查一下「{city} 月出时间」，查不了就等它自己上来。"
